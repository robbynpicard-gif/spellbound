/**
 * D-097: classic vs director difficulty, measured on what actually spawns
 * when a bot typist plays sample levels. Writes a markdown report.
 *
 *   node --experimental-transform-types tools/difficulty/compare.ts > report.md
 *   (or through the repo's test harness loader)
 */
import { WORDS } from '../../src/data/wordList';
import { demand, percentile, quadrantOf, simulateLevel, type BotSkill, type SimResult, type SimSpawn } from '../../src/difficulty/DirectorSimulation';
import { BOSS_LEVEL, trialLevel, type DifficultySystem, type Mode } from '../../src/typel/apprenticeship';
import { DifficultyDirector, journeyPosition, LENGTH_BANDS, SPEED_BANDS } from '../../src/difficulty/DifficultyDirector';
import { FIELD } from '../../src/core/GameConfig';

const SEEDS = [1, 2, 3, 4, 5, 6];
const LEVELS = [1, 4, 8, 12, BOSS_LEVEL];
const TRIALS = [1, 5, 9];
const BOT: Record<Mode, BotSkill> = { normal: { cps: 4.0, reaction: 0.35 }, hardcore: { cps: 5.0, reaction: 0.3 } };

interface Row {
  spawns: SimSpawn[];
  sims: SimResult[];
}

function run(mode: Mode, trial: number, system: DifficultySystem, levels = LEVELS): Row {
  const sims: SimResult[] = [];
  for (const level of levels) for (const seed of SEEDS) sims.push(simulateLevel(trialLevel(mode, trial, level, system), seed * 7919 + level, WORDS, BOT[mode], 240));
  return { sims, spawns: sims.flatMap((s) => s.spawns) };
}

const pct = (x: number) => `${Math.round(x * 100)}%`;
const f1 = (x: number) => x.toFixed(1);

function stats(row: Row, skill: BotSkill) {
  const sp = row.spawns;
  const lens = sp.map((s) => s.length);
  const falls = sp.map((s) => s.fallSeconds);
  const q: Record<string, number> = {};
  for (const s of sp) q[quadrantOf(s)] = (q[quadrantOf(s)] ?? 0) + 1;
  const ratio = sp.map((s) => s.fallSeconds / (s.length / skill.cps + skill.reaction));
  // in-level curve: mean demand per fifth of the encounter, relative to the first fifth
  const fifths = [0, 1, 2, 3, 4].map((k) => {
    const xs = sp.filter((s) => Math.min(4, Math.floor(s.progress * 5)) === k).map(demand);
    return xs.reduce((a, b) => a + b, 0) / Math.max(1, xs.length);
  });
  const minutes = row.sims.reduce((a, s) => a + s.seconds, 0) / 60;
  const top = percentile(sp.map(demand), 0.75);
  // calm windows: 5-second windows with no top-quartile-demand spawn
  let windows = 0;
  let calm = 0;
  for (const sim of row.sims)
    for (let t = 0; t + 5 <= sim.seconds; t += 5) {
      windows++;
      if (!sim.spawns.some((s) => s.t >= t && s.t < t + 5 && demand(s) >= top)) calm++;
    }
  return {
    n: sp.length,
    lenMed: percentile(lens, 0.5), lenP10: percentile(lens, 0.1), lenP90: percentile(lens, 0.9),
    short: lens.filter((l) => l <= 4).length / sp.length, long: lens.filter((l) => l >= 7).length / sp.length,
    fallP10: percentile(falls, 0.1), fallMed: percentile(falls, 0.5), fallP90: percentile(falls, 0.9),
    quads: (['short-slow', 'long-slow', 'short-fast', 'long-fast'] as const).map((k) => (q[k] ?? 0) / sp.length),
    ratioP10: percentile(ratio, 0.1), tight: ratio.filter((r) => r < 2).length / sp.length,
    curve: fifths.map((v) => v / (fifths[0] || 1)),
    shortSlowPerMin: (q['short-slow'] ?? 0) / minutes,
    calm: calm / Math.max(1, windows),
    breachesPerLevel: row.sims.reduce((a, s) => a + s.breaches, 0) / row.sims.length,
    won: row.sims.filter((s) => s.result === 'won').length / row.sims.length,
  };
}

const out: string[] = [];
out.push('# D-097 simulation: classic vs Difficulty Director');
out.push(`_Generated by \`tools/difficulty/compare.ts\`. Bot typist (never casts spells, aims at the lowest word): Normal ${BOT.normal.cps} chars/s with a ${BOT.normal.reaction}s pause; Hardcore ${BOT.hardcore.cps} chars/s, ${BOT.hardcore.reaction}s. Sample levels ${LEVELS.join(', ')} (13 = boss) × ${SEEDS.length} seeds per apprenticeship. All director numbers are EXPERIMENTAL._`);
out.push('');
out.push('**Quadrants** use fixed thresholds: short ≤ 4 letters, long ≥ 7; slow = falls the field in ≥ 12 s, fast ≤ 9 s. **Time-to-Ward ratio** = fall time ÷ the bot\'s time to type the word (below 2 counts as tight). **In-level curve** = average typing demand (letters per second of fall) in each fifth of an encounter, relative to the first fifth: a straight ramp grows evenly; a convex arc saves most of its growth for the end. **Calm windows** = share of 5-second stretches with no top-quartile-demand word.');
for (const mode of ['normal', 'hardcore'] as const) {
  out.push('');
  out.push(`## ${mode === 'normal' ? 'Normal' : 'Hardcore'}`);
  out.push('');
  out.push('| Apprenticeship | System | Words | Length p10 / median / p90 | ≤4 / ≥7 letters | Fall s p10 / median / p90 | Short-slow · Long-slow · Short-fast · Long-fast | Time-to-Ward ratio p10 · tight | In-level curve (5 fifths) | Short-slow per min | Calm windows | Bot breaches / level · levels won |');
  out.push('|---|---|---|---|---|---|---|---|---|---|---|---|');
  for (const trial of TRIALS)
    for (const system of ['classic', 'director'] as const) {
      const s = stats(run(mode, trial, system), BOT[mode]);
      out.push(`| ${trial} | ${system} | ${s.n} | ${s.lenP10} / ${s.lenMed} / ${s.lenP90} | ${pct(s.short)} / ${pct(s.long)} | ${f1(s.fallP10)} / ${f1(s.fallMed)} / ${f1(s.fallP90)} | ${s.quads.map(pct).join(' · ')} | ${f1(s.ratioP10)} · ${pct(s.tight)} | ${s.curve.map((v) => v.toFixed(2)).join(' ')} | ${f1(s.shortSlowPerMin)} | ${pct(s.calm)} | ${f1(s.breachesPerLevel)} · ${pct(s.won)} |`);
    }
}
out.push('');
out.push('## The director\'s own curves (Normal)');
out.push('');
out.push('**Pressure through an encounter** (0 = calm, 1 = peak). Relief windows sit near 42% and 74%.');
out.push('');
out.push('| Encounter | 0% | 20% | 40% | 42% (relief) | 60% | 74% (relief) | 80% | 90% | 100% |');
out.push('|---|---|---|---|---|---|---|---|---|---|');
for (const [label, trial, level] of [['Apprenticeship 1, level 6', 1, 6], ['Apprenticeship 5, level 6', 5, 6], ['Apprenticeship 9, level 6', 9, 6], ['Apprenticeship 9, boss', 9, 13]] as const) {
  const d = new DifficultyDirector({ mode: 'normal', position: journeyPosition(trial, level), encounter: level === 13 ? 'boss' : 'level' }, FIELD.height);
  out.push(`| ${label} | ${[0, 0.2, 0.4, 0.42, 0.6, 0.74, 0.8, 0.9, 1].map((p) => d.pressure(p).toFixed(2)).join(' | ')} |`);
}
out.push('');
out.push('**Joint length × speed mix** (share of spawns) at an encounter\'s calm opening and its peak. Rows are word length; columns are speed.');
for (const [label, position] of [['First apprenticeship', 0], ['Last apprenticeship', 1]] as const) {
  const d = new DifficultyDirector({ mode: 'normal', position, encounter: 'level' }, FIELD.height);
  for (const [when, p] of [['opening', 0], ['peak', 1]] as const) {
    const m = d.joint(d.pressure(p));
    const secs = SPEED_BANDS.map((b) => d.bandSeconds(b, p).toFixed(1));
    out.push('');
    out.push(`_${label}, ${when}: slow ≈ ${secs[0]} s, medium ≈ ${secs[1]} s, fast ≈ ${secs[2]} s to fall the field_`);
    out.push('');
    out.push('| | slow | medium | fast |');
    out.push('|---|---|---|---|');
    LENGTH_BANDS.forEach((band, i) => {
      const [lo, hi] = d.lengthRange(band);
      out.push(`| ${band} (${lo}–${hi}) | ${m[i]!.map((v) => pct(v)).join(' | ')} |`);
    });
  }
}
console.log(out.join('\n'));
